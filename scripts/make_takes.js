// Packs ElevenLabs word timings (vo_<n>.json) into <project>/takes.js, read by score.js in Node and the browser.
//   node make_takes.js <project>/assets
const fs = require('fs');
const path = require('path');
const dir = path.resolve(process.argv[2] || 'assets');
const takes = [];
for (let i = 1; fs.existsSync(path.join(dir, `vo_${i}.json`)); i++) {
  const j = JSON.parse(fs.readFileSync(path.join(dir, `vo_${i}.json`), 'utf8'));
  takes.push({ text: j.text, len: j.duration, words: j.words });
}
if (!takes.length) { console.error(`no vo_<n>.json in ${dir}`); process.exit(1); }
const out = `// generated by make_takes.js from the ElevenLabs alignments: do not edit by hand
(function () { const TAKES = ${JSON.stringify(takes)};
  if (typeof module !== 'undefined') module.exports = TAKES; else globalThis.TAKES = TAKES; })();
`;
fs.writeFileSync(path.join(dir, '..', 'takes.js'), out);
console.log(`takes.js: ${takes.length} takes, ${takes.reduce((a, t) => a + t.len, 0).toFixed(1)}s of speech`);
